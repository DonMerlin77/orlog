"""
orlog/agents/store_learner.py — Feed the store's agent architecture into Orlog's brain.

Reads key store files, extracts reusable architectural patterns via Claude,
and appends them to orlog/app/store_patterns.md — a brain layer Orlog can
reference when reasoning about agent design, scheduling, API patterns, etc.

Run:
    python3 -m orlog.agents.store_learner              # learn from all key files
    python3 -m orlog.agents.store_learner --file agents/listing_agent.py
    python3 -m orlog.agents.store_learner --report     # show what's been learned
"""

import os
import sys
import json
import argparse
from pathlib import Path
from datetime import datetime

from dotenv import load_dotenv

sys.path.insert(0, str(Path(__file__).parents[2]))
from llm_router import fast_call

load_dotenv(Path(__file__).parents[2] / ".env")

STORE_ROOT    = Path(__file__).parents[2]
PATTERNS_PATH = Path(__file__).parents[1] / "app" / "store_patterns.md"
LEARN_LOG     = Path("logs/store_learner.json")

# Key store files that contain reusable architectural wisdom
KEY_FILES = [
    "agents/agent_brain.py",
    "agents/cj_connection.py",
    "agents/listing_agent.py",
    "agents/marketing_agent.py",
    "agents/trend_agent.py",
    "agents/teach.py",
    "agents/notify.py",
    "intelligence/shared/analyze_text.py",
    "intelligence/shared/synthesize.py",
    "scheduler_agent.py",
    "shopify_wrapper.py",
    "orlog/hermes/hermes.py",
    "orlog/mirror/mirror.py",
    "orlog/eval/adversarial.py",
    "orlog/eval/constitution.py",
    "orlog/scheduler/scheduler.py",
]

EXTRACT_SYSTEM = """You are an architectural analyst reading production Python code.

Extract exactly 5 reusable lessons from this file. Each lesson must be:
- A specific, actionable pattern (not a generic observation)
- Applicable to building other AI agents or tools
- Named clearly so it can be referenced later

Format each lesson exactly as:
PATTERN [name]: [what it does and when to use it — 2 sentences max]

Focus on: error handling patterns, API design decisions, cost control, agent orchestration,
brain/prompt injection, scheduling, feedback loops, self-improvement mechanisms.
Ignore boilerplate, imports, and obvious Python."""


def _extract_patterns(filepath: str, content: str) -> list[str]:
    raw = fast_call(
        EXTRACT_SYSTEM,
        f"File: {filepath}\n\n```python\n{content[:6000]}\n```",
        600,
    )
    patterns = []
    for line in raw.splitlines():
        if line.startswith("PATTERN "):
            patterns.append(line.strip())
    return patterns


def _append_to_brain(filepath: str, patterns: list[str]):
    if not patterns:
        return
    header = f"\n\n## From `{filepath}` — {datetime.now().strftime('%Y-%m-%d')}\n"
    block  = "\n".join(f"- {p}" for p in patterns)
    with PATTERNS_PATH.open("a") as f:
        f.write(header + block + "\n")


def _load_log() -> dict:
    if LEARN_LOG.exists():
        try:
            return json.loads(LEARN_LOG.read_text())
        except Exception:
            pass
    return {"learned": []}


def _save_log(log: dict):
    LEARN_LOG.parent.mkdir(exist_ok=True)
    LEARN_LOG.write_text(json.dumps(log, indent=2))


def learn_file(filepath: str, force: bool = False) -> list[str]:
    log = _load_log()
    already_learned = [e["file"] for e in log["learned"]]

    if filepath in already_learned and not force:
        print(f"  Already learned — skip (use --force to re-run)")
        return []

    full_path = STORE_ROOT / filepath
    if not full_path.exists():
        print(f"  File not found: {full_path}")
        return []

    content = full_path.read_text(encoding="utf-8", errors="ignore")
    print(f"  Extracting patterns from {filepath} ({len(content)} chars)...")

    patterns = _extract_patterns(filepath, content)
    if patterns:
        _append_to_brain(filepath, patterns)
        log["learned"].append({
            "file":     filepath,
            "patterns": patterns,
            "ts":       datetime.now().isoformat(),
        })
        _save_log(log)
        print(f"  {len(patterns)} patterns written to store_patterns.md")
    else:
        print(f"  No patterns extracted")

    return patterns


def learn_all(force: bool = False):
    if not PATTERNS_PATH.exists():
        PATTERNS_PATH.write_text(
            "# Store Patterns — Architectural lessons from Continuum Goods agent stack\n"
            "> Auto-generated by store_learner.py. Injected into Orlog's reasoning context.\n"
        )

    print(f"Learning from {len(KEY_FILES)} store files...\n")
    total = 0
    for filepath in KEY_FILES:
        print(f"[{filepath}]")
        patterns = learn_file(filepath, force=force)
        total += len(patterns)

    print(f"\nDone. {total} total patterns written to {PATTERNS_PATH}")


def report():
    log = _load_log()
    learned = log.get("learned", [])
    if not learned:
        print("Nothing learned yet. Run without --report first.")
        return

    print(f"\n{'='*60}")
    print(f"STORE LEARNER REPORT — {len(learned)} files processed")
    print(f"{'='*60}")
    for entry in learned:
        print(f"\n{entry['file']} ({entry['ts'][:10]})")
        for p in entry["patterns"]:
            print(f"  {p[:90]}")


def main():
    parser = argparse.ArgumentParser(description="Learn from store agent architecture")
    parser.add_argument("--file",   help="Learn from a single file path")
    parser.add_argument("--force",  action="store_true", help="Re-learn already-learned files")
    parser.add_argument("--report", action="store_true", help="Print what's been learned")
    args = parser.parse_args()

    import sys
    sys.path.insert(0, str(STORE_ROOT))

    if args.report:
        report()
    elif args.file:
        learn_file(args.file, force=args.force)
    else:
        learn_all(force=args.force)


if __name__ == "__main__":
    main()
