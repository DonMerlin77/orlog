class DomainBuilder(Builder):

    def _generate_scaffolding(self, result: dict, out: Path) -> list[Path]:
        verdict   = result.get("synthesis", {}).get("verdict", "")
        goal      = result.get("goal", "")
        synthesis = result.get("synthesis_raw", "")

        files = []

        # Schema directory
        schema_dir = out / "schema"
        schema_dir.mkdir(exist_ok=True)

        files += self._write_schema(schema_dir, goal, verdict, synthesis)
        files += self._write_godot_starters(out / "godot", goal, verdict)
        files += self._write_server_starters(out / "server", goal, verdict)

        return files

    def _write_schema(self, schema_dir: Path, goal: str, verdict: str, synthesis: str) -> list[Path]:
        prompt = (
            f"You are generating PostgreSQL/Supabase schema SQL for a game with this architecture:\n\n"
            f"Goal: {goal[:500]}\n\n"
            f"Key architectural decision: {verdict}\n\n"
            f"Build order context:\n{synthesis[:1000]}\n\n"
            f"Generate THREE separate SQL files:\n"
            f"1. regions.sql — region ownership, one player per region enforcement at write time, "
            f"region state (active/abandoned), timestamp tracking\n"
            f"2. traces.sql — async player traces (bases, camps, flags, loot), "
            f"owner_id, region_id, trace_type, created_at, last_seen\n"
            f"3. respawn.sql — permanent respawn choices (immutable once set), "
            f"player_id, region_id, choice_type (continue/restart), chosen_at\n\n"
            f"Each file: clean SQL with comments. Include Row Level Security policies "
            f"for Supabase. No explanations outside the SQL."
        )
        raw = self._claude_generate(prompt, max_tokens=2000)

        files = []
        sections = {"regions.sql": "", "traces.sql": "", "respawn.sql": ""}
        current = None
        buffer  = []

        for line in raw.split("\n"):
            low = line.strip().lower()
            matched = next((k for k in sections if k in low and (line.strip().startswith("--") or "file" in low)), None)
            if matched:
                if current and buffer:
                    sections[current] = "\n".join(buffer)
                current = matched
                buffer  = [line]
            elif current:
                buffer.append(line)

        if current and buffer:
            sections[current] = "\n".join(buffer)

        for fname, content in sections.items():
            if not content.strip():
                content = f"-- {fname} — generated by Orlog\n-- TODO: fill based on BUILD_ORDER.md\n"
            p = schema_dir / fname
            p.write_text(content)
            files.append(p)

        return files

    def _write_godot_starters(self, godot_dir: Path, goal: str, verdict: str) -> list[Path]:
        godot_dir.mkdir(exist_ok=True)
        prompt = (
            f"You are generating GDScript 4 (Godot 4) starter files for a multiplayer game.\n\n"
            f"Architecture decision: {verdict}\n\n"
            f"Game concept: {goal[:400]}\n\n"
            f"Generate TWO GDScript files:\n\n"
            f"1. RegionManager.gd — Autoload singleton. Handles:\n"
            f"   - Requesting region entry from server (async, awaits confirmation)\n"
            f"   - Blocking entry if region is occupied\n"
            f"   - Emitting signals: region_entered, region_denied, region_exited\n"
            f"   - Polling region state every 30s to detect if another player claims it\n\n"
            f"2. TraceSystem.gd — Autoload singleton. Handles:\n"
            f"   - Writing player traces (place_trace(type, position)) to server\n"
            f"   - Reading traces in current region (get_region_traces())\n"
            f"   - Trace types: BASE, CAMP, FLAG, LOOT_CACHE\n"
            f"   - Async — uses Supabase REST API via HTTPRequest\n\n"
            f"Use GDScript 4 syntax. Include signal definitions, basic error handling, "
            f"and TODO comments where game-specific logic needs to be filled in. "
            f"Use placeholder constants for server URL and API key."
        )
        raw = self._claude_generate(prompt, max_tokens=2000)

        files = []
        current_file = None
        buffer       = []
        file_map     = {"RegionManager.gd": "", "TraceSystem.gd": ""}

        for line in raw.split("\n"):
            matched = next((k for k in file_map if k in line), None)
            if matched and (line.strip().startswith("#") or "##" in line or "file" in line.lower()):
                if current_file and buffer:
                    file_map[current_file] = "\n".join(buffer)
                current_file = matched
                buffer       = []
            elif current_file:
                buffer.append(line)

        if current_file and buffer:
            file_map[current_file] = "\n".join(buffer)

        for fname, content in file_map.items():
            if len(content.strip()) < 50:
                content = self._fallback_gdscript(fname)
            p = godot_dir / fname
            p.write_text(content)
            files.append(p)

        project_cfg = godot_dir / "project.godot"
        project_cfg.write_text(self._godot_project_cfg())
        files.append(project_cfg)

        return files

