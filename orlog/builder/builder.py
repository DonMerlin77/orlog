"""
orlog/builder/ — Execution layer. Takes an Orlog verdict and generates
real project scaffolding that a developer can start from immediately.

Orlog tells you what to build and in what order.
Builder turns that into files on disk.

Usage:
    from orlog.core import Orlog
    from orlog.builder import build_for_domain

    o = Orlog(goal="Build Coeus...", domain="game_dev")
    result = o.run("What's the build order?", task_type="strategy")
    output_path = build_for_domain(result, output_dir="~/projects/coeus")
    # output_path has schema/, starter code, BUILD_ORDER.md
"""

import os
import json
import importlib
from datetime import datetime
from pathlib import Path
from dotenv import load_dotenv

import sys as _sys
_sys.path.insert(0, str(Path(__file__).parents[2]))
from llm_router import quality_call

load_dotenv(Path(__file__).parent.parent.parent / ".env")


class Builder:
    """
    Base builder. Generates scaffolding from an Orlog result dict.
    Subclass per domain for domain-specific file generation.
    """

    def __init__(self, api_key: str = None):
        pass

    def build(self, result: dict, output_dir: str) -> Path:
        out = Path(output_dir).expanduser()
        out.mkdir(parents=True, exist_ok=True)

        self._write_build_order(result, out)
        self._write_architecture_notes(result, out)
        files = self._generate_scaffolding(result, out)

        manifest = {
            "generated_at": datetime.now().isoformat(),
            "domain":        result.get("domain"),
            "goal":          result.get("goal", "")[:200],
            "orlog_score":   result.get("orlog_score"),
            "verdict":       result.get("synthesis", {}).get("verdict", "")[:300],
            "files":         [str(f.relative_to(out)) for f in files],
        }
        (out / "orlog_manifest.json").write_text(json.dumps(manifest, indent=2))

        return out

    def _write_build_order(self, result: dict, out: Path):
        synthesis = result.get("synthesis", {})
        verdict       = synthesis.get("verdict", "")
        key_tension   = synthesis.get("key_tension", "")
        blind_spot    = synthesis.get("blind_spot", "")
        synthesis_raw = result.get("synthesis_raw", "")

        content = f"""# BUILD ORDER
> Generated by Orlog on {datetime.now().strftime('%Y-%m-%d')}
> Domain: {result.get('domain', 'unknown')} | Score: {result.get('orlog_score', 'n/a')}/10

---

## VERDICT

{verdict}

---

## KEY TENSION

{key_tension}

---

## BLIND SPOT

{blind_spot}

---

## FULL ORLOG OUTPUT

{synthesis_raw}

---

## LENSES USED

{chr(10).join(f'- {l}' for l in result.get('lenses', []))}

## AGENTS SELECTED

{chr(10).join(f'- {a}' for a in result.get('agents', []))}
"""
        (out / "BUILD_ORDER.md").write_text(content)

    def _write_architecture_notes(self, result: dict, out: Path):
        """Generate ADR (Architecture Decision Record) for the key decision."""
        verdict = result.get("synthesis", {}).get("verdict", "")
        if not verdict:
            return

        adr = f"""# ADR-001: Foundational Architecture Decision
> Date: {datetime.now().strftime('%Y-%m-%d')}
> Status: ACCEPTED (Orlog recommendation, score {result.get('orlog_score', 'n/a')}/10)

## Decision

{verdict}

## Context

Goal: {result.get('goal', '')[:300]}

## Consequences

- All subsequent systems assume this decision is infallible
- Rebuilding this layer requires rebuilding dependent systems
- Document any deviation from this decision in ADR-002+

## Review Trigger

If this decision proves wrong, open ADR-002 with: what broke, what was missed, what the correct decision is.
"""
        (out / "ADR-001.md").write_text(adr)

    def _generate_scaffolding(self, result: dict, out: Path) -> list[Path]:
        """Override in domain subclasses. Returns list of generated file paths."""
        return []

    def _claude_generate(self, prompt: str, max_tokens: int = 1500) -> str:
        return quality_call("", prompt, max_tokens)


def build_for_domain(result: dict, output_dir: str, api_key: str = None) -> Path:
    """
    Auto-selects the right domain builder and runs it.
    Falls back to base Builder if no domain-specific builder exists.
    """
    domain = result.get("domain", "generic")
    try:
        mod     = importlib.import_module(f"orlog.builder.{domain}")
        builder = mod.DomainBuilder(api_key=api_key)
    except (ModuleNotFoundError, AttributeError):
        builder = Builder(api_key=api_key)

    return builder.build(result, output_dir)
