"""
orlog/builder/stores.py — Shopify store scaffolding generator.

Generates:
  copy/              — Product copy template, email sequences (welcome + abandoned cart)
  collections/       — Collection structure strategy
  ops/               — Pricing model (Python)
  launch/            — Launch checklist
  BUILD_ORDER.md     — Orlog verdict as actionable phases (base class)
  ADR-001.md         — Architecture Decision Record (base class)
"""

from pathlib import Path
from .builder import Builder


class DomainBuilder(Builder):

    def _generate_scaffolding(self, result: dict, out: Path) -> list[Path]:
        verdict   = result.get("synthesis", {}).get("verdict", "")
        goal      = result.get("goal", "")
        synthesis = result.get("synthesis_raw", "")

        files = []

        copy_dir        = out / "copy";        copy_dir.mkdir(exist_ok=True)
        collections_dir = out / "collections"; collections_dir.mkdir(exist_ok=True)
        ops_dir         = out / "ops";         ops_dir.mkdir(exist_ok=True)
        launch_dir      = out / "launch";      launch_dir.mkdir(exist_ok=True)

        files += self._write_product_copy(copy_dir, goal, verdict, synthesis)
        files += self._write_email_sequences(copy_dir, goal, verdict)
        files += self._write_collection_structure(collections_dir, goal, verdict, synthesis)
        files += self._write_pricing_model(ops_dir, goal, verdict)
        files += self._write_launch_checklist(launch_dir, goal, verdict, synthesis)

        return files

    # ── Product copy ──────────────────────────────────────────────────────────

    def _write_product_copy(self, copy_dir: Path, goal: str, verdict: str, synthesis: str) -> list[Path]:
        prompt = (
            f"You are generating a Shopify product copy template for a store with this strategy:\n\n"
            f"Goal: {goal[:500]}\n\n"
            f"Strategic verdict: {verdict}\n\n"
            f"Build context:\n{synthesis[:800]}\n\n"
            f"Generate a reusable product copy template using StoryBrand + Hormozi frameworks:\n"
            f"- Customer = hero, product = guide\n"
            f"- Title: dream outcome headline (under 60 chars, specific, identity-first)\n"
            f"- Hook: one sentence — the problem the customer lives with daily\n"
            f"- Body: 3-4 sentences — what changes after they own this, concrete outcomes\n"
            f"- Proof point: one specific claim (stat, origin, or process detail)\n"
            f"- CTA: action phrase tied to transformation, not features\n"
            f"- Tags: 6-8 SEO tags as comma-separated list\n\n"
            f"Include:\n"
            f"1. A filled example using a real product type appropriate for this store\n"
            f"2. A blank template with [PLACEHOLDER] markers for each field\n"
            f"3. A 'Copy Rules' section: 5 store-specific rules derived from the verdict\n\n"
            f"Format as clean markdown. No generic advice — make it specific to this store's strategy."
        )
        content = self._claude_generate(prompt, max_tokens=1500)
        if len(content.strip()) < 100:
            content = self._fallback_product_copy(goal)

        p = copy_dir / "product_template.md"
        p.write_text(content)
        return [p]

    def _fallback_product_copy(self, goal: str) -> str:
        return f"""# Product Copy Template
> Generated by Orlog for: {goal[:100]}

## Copy Rules
1. Customer is the hero — never say "our product"
2. Lead with transformation, not features
3. Dream outcome headline under 60 characters
4. One proof point per listing (stat, origin, or process)
5. CTA is an action tied to identity, not a purchase

---

## Example (fill in for your hero product)

**Title:** [Dream outcome in under 60 chars]

**Hook:** [The problem they live with every day — one sentence]

**Body:**
[What changes after they own this. 3-4 sentences. Concrete, specific.]

**Proof:** [One claim: stat, origin story, or how it's made]

**CTA:** [Action phrase — not "Buy now", but "Start/Get/Claim [transformation]"]

**Tags:** [tag1, tag2, tag3, tag4, tag5, tag6]
"""

    # ── Email sequences ───────────────────────────────────────────────────────

    def _write_email_sequences(self, copy_dir: Path, goal: str, verdict: str) -> list[Path]:
        prompt = (
            f"You are generating two Shopify email templates for a store with this strategy:\n\n"
            f"Goal: {goal[:400]}\n\n"
            f"Strategic verdict: {verdict}\n\n"
            f"Generate:\n\n"
            f"## EMAIL 1: Welcome Email (sent immediately on signup)\n"
            f"- Subject line: curiosity + identity, under 45 chars\n"
            f"- Preview text: completes the subject, under 90 chars\n"
            f"- Body: warm, specific to the store's niche, 3 short paragraphs\n"
            f"- CTA: single action, tied to the store's hero collection or product\n"
            f"- Tone: conversational, not corporate\n\n"
            f"## EMAIL 2: Abandoned Cart (sent 1 hour after abandonment)\n"
            f"- Subject line: gentle callback, no guilt, under 45 chars\n"
            f"- Preview text: under 90 chars\n"
            f"- Body: 2 paragraphs — remind them what they almost had, remove friction\n"
            f"- CTA: return to cart\n"
            f"- Optional: one-line social proof or urgency hook\n\n"
            f"Format as clean markdown with clear EMAIL 1 / EMAIL 2 sections."
        )
        content = self._claude_generate(prompt, max_tokens=1200)
        if len(content.strip()) < 100:
            content = self._fallback_emails()

        p = copy_dir / "email_sequences.md"
        p.write_text(content)
        return [p]

    def _fallback_emails(self) -> str:
        return """# Email Sequences
> Generated by Orlog

## EMAIL 1: Welcome

**Subject:** You found us. Here's what's inside.
**Preview:** The stuff we actually stand behind — and why.

**Body:**
Welcome. We're glad you're here.

[2-3 sentences about who your store is for and what makes it different from everywhere else.]

Your first stop: [hero collection or product name]. Start there.

**CTA:** [Explore / See / Discover] → [collection URL]

---

## EMAIL 2: Abandoned Cart

**Subject:** Still thinking it over?
**Preview:** It's still in your cart. No pressure, just checking.

**Body:**
You left something behind — and we get it. You're busy, or you wanted to think.

[1-2 sentences removing the friction: easy returns, fast shipping, or what makes this worth it.]

**CTA:** Complete your order → [cart URL]

**Proof line:** [Optional: "X people bought this last week" or "Ships in 2 days"]
"""

    # ── Collection structure ──────────────────────────────────────────────────

    def _write_collection_structure(self, collections_dir: Path, goal: str, verdict: str, synthesis: str) -> list[Path]:
        prompt = (
            f"You are designing Shopify collection structure for a store with this strategy:\n\n"
            f"Goal: {goal[:400]}\n\n"
            f"Verdict: {verdict}\n\n"
            f"Context:\n{synthesis[:600]}\n\n"
            f"Generate a collection structure document with:\n\n"
            f"1. **Primary Collections** (3-6): Name, one-line description, what belongs here, "
            f"what does NOT belong here, hero product archetype\n\n"
            f"2. **Collection Naming Rules**: 3-4 rules for naming collections "
            f"(identity-first, audience-led, not product-category-led)\n\n"
            f"3. **Tagging Strategy**: how to tag products so they appear in the right collections "
            f"and search results. Include: required tags, optional tags, tags to avoid\n\n"
            f"4. **Homepage Layout Recommendation**: which collections go above the fold, "
            f"in what order, and why (based on the verdict)\n\n"
            f"Format as structured markdown. Be specific — no generic 'Men' / 'Women' categories."
        )
        content = self._claude_generate(prompt, max_tokens=1200)
        if len(content.strip()) < 100:
            content = "# Collection Structure\n\n> TODO: fill based on BUILD_ORDER.md verdict\n"

        p = collections_dir / "structure.md"
        p.write_text(content)
        return [p]

    # ── Pricing model ─────────────────────────────────────────────────────────

    def _write_pricing_model(self, ops_dir: Path, goal: str, verdict: str) -> list[Path]:
        content = f'''"""
ops/pricing_model.py — Shopify pricing calculator.
Generated by Orlog for: {goal[:120]}

Strategy: {verdict[:200]}

Adjust MARGIN_TARGET and SHIPPING_BUFFER for your supplier and category.
"""

# ── Config — edit these for your store ───────────────────────────────────────

MARGIN_TARGET   = 0.45   # 45% gross margin minimum
SHIPPING_BUFFER = 4.50   # avg shipping cost added to COGS
PLATFORM_FEE    = 0.029  # Shopify Payments (2.9% + 30¢)
PLATFORM_FIXED  = 0.30

PRICE_FLOORS = {{
    "low":    9.99,   # below this: not worth listing
    "mid":   24.99,   # sweet spot for impulse buys
    "high":  59.99,   # considered purchase, needs strong copy
}}

# ── Core formula ─────────────────────────────────────────────────────────────

def target_price(cogs: float, shipping: float = None) -> float:
    """
    Return the minimum retail price to hit MARGIN_TARGET after fees.
    cogs: cost of goods from supplier (no shipping)
    """
    total_cost = cogs + (shipping if shipping is not None else SHIPPING_BUFFER)
    # price = total_cost / (1 - margin - platform_fee)
    price = total_cost / (1 - MARGIN_TARGET - PLATFORM_FEE)
    price -= PLATFORM_FIXED  # fixed fee doesn't scale — small adjustment
    return round(max(price, PRICE_FLOORS["low"]), 2)


def margin(retail: float, cogs: float, shipping: float = None) -> float:
    """Actual gross margin at a given retail price."""
    total_cost = cogs + (shipping if shipping is not None else SHIPPING_BUFFER)
    fee = retail * PLATFORM_FEE + PLATFORM_FIXED
    return round((retail - total_cost - fee) / retail, 4)


def price_tier(retail: float) -> str:
    if retail < PRICE_FLOORS["mid"]:    return "low"
    if retail < PRICE_FLOORS["high"]:   return "mid"
    return "high"


def audit(cogs: float, current_price: float, shipping: float = None) -> dict:
    """Full audit: current margin, target price, recommendation."""
    m       = margin(current_price, cogs, shipping)
    target  = target_price(cogs, shipping)
    deficit = target - current_price

    return {{
        "cogs":           cogs,
        "current_price":  current_price,
        "current_margin": f"{{m:.1%}}",
        "target_price":   target,
        "deficit":        round(deficit, 2),
        "recommendation": "OK" if deficit <= 0 else f"Raise price by ${{deficit:.2f}}",
        "tier":           price_tier(current_price),
    }}


# ── CLI ───────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    import sys
    if len(sys.argv) >= 3:
        cogs  = float(sys.argv[1])
        price = float(sys.argv[2])
        ship  = float(sys.argv[3]) if len(sys.argv) > 3 else None
        result = audit(cogs, price, ship)
        for k, v in result.items():
            print(f"  {{k:20}} {{v}}")
    else:
        print("Usage: python3 pricing_model.py <cogs> <current_price> [shipping]")
        print("Example: python3 pricing_model.py 8.50 24.99")
'''
        p = ops_dir / "pricing_model.py"
        p.write_text(content)
        return [p]

    # ── Launch checklist ─────────────────────────────────────────────────────

    def _write_launch_checklist(self, launch_dir: Path, goal: str, verdict: str, synthesis: str) -> list[Path]:
        prompt = (
            f"You are generating a Shopify store launch checklist based on this strategy:\n\n"
            f"Goal: {goal[:400]}\n\n"
            f"Verdict: {verdict}\n\n"
            f"Context:\n{synthesis[:600]}\n\n"
            f"Generate a launch checklist with these phases:\n\n"
            f"**Phase 1 — Foundation** (must be done before any traffic)\n"
            f"**Phase 2 — First Traffic** (minimum viable to start driving visitors)\n"
            f"**Phase 3 — Conversion** (optimize once traffic exists)\n"
            f"**Phase 4 — Retention** (once first sales exist)\n\n"
            f"Each phase: 4-7 specific, actionable checklist items.\n"
            f"No generic advice. Each item should be specific to the store's strategy and verdict.\n"
            f"Mark the single most important item in each phase with [KEYSTONE].\n\n"
            f"Format as markdown checkboxes (- [ ] item)."
        )
        content = self._claude_generate(prompt, max_tokens=1000)
        if len(content.strip()) < 100:
            content = self._fallback_checklist()

        p = launch_dir / "launch_checklist.md"
        p.write_text(content)
        return [p]

    def _fallback_checklist(self) -> str:
        return """# Launch Checklist
> Generated by Orlog

## Phase 1 — Foundation
- [ ] [KEYSTONE] Publish hero collection with 10+ products, each with full StoryBrand copy
- [ ] Set up abandoned cart email (1h delay)
- [ ] Add email capture popup with lead magnet
- [ ] Configure shipping rates and return policy
- [ ] Set all products to inventory_policy=continue

## Phase 2 — First Traffic
- [ ] [KEYSTONE] Post 3x/week on the platform your audience lives on
- [ ] Submit store to Google Shopping
- [ ] Pin hero products to Pinterest
- [ ] Set up Google Analytics 4

## Phase 3 — Conversion
- [ ] [KEYSTONE] Add social proof (reviews app — Judge.me free tier)
- [ ] A/B test hero product headline
- [ ] Add urgency element to top 3 products
- [ ] Optimize product images (lifestyle > white background)

## Phase 4 — Retention
- [ ] [KEYSTONE] Launch welcome email series (3 emails, 3-day cadence)
- [ ] Segment email list by purchase category
- [ ] Set up win-back flow (90 days no purchase)
- [ ] Add loyalty program or referral incentive
"""
